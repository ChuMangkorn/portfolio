// Writes lib/worklog-stats.ts from the anonymised work log. Counts only: no text from the log reaches the repo.
// Usage: npm run worklog:stats -- "<vault>/Work Log"
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { countWorkLog } from "../lib/worklog-count.ts";

const dir = process.argv[2];
if (!dir) {
  console.error('usage: npm run worklog:stats -- "<vault>/Work Log"');
  process.exit(1);
}

// Monthly files only: not the README, the drafts or the private name key.
const files = readdirSync(dir)
  .map((name) => /^work-log-(\d{4}-\d{2})\.md$/.exec(name))
  .filter((m): m is RegExpExecArray => m !== null)
  .map((m) => ({ month: m[1], text: readFileSync(join(dir, m[0]), "utf8") }));

const today = new Date();
const asOf = [today.getFullYear(), today.getMonth() + 1, today.getDate()].map((n) => String(n).padStart(2, "0")).join("-");
const stats = countWorkLog(files, asOf);

const out = new URL("../lib/worklog-stats.ts", import.meta.url);
writeFileSync(
  out,
  `// Generated by scripts/worklog-stats.ts from the anonymised work log. Counts only. Do not edit.
import type { WorklogStats } from "./worklog-count.ts";

export const worklogStats: WorklogStats = ${JSON.stringify(stats, null, 2)};
`,
);
console.log(`${files.length} month files: ${stats.total} logged (${stats.cases} cases, ${stats.routine} routine), since ${stats.since}`);
console.log(stats.byType);
